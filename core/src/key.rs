const AUTO_CALIBRATION: Calibration = Calibration { slope: 1.041, offset: 0.586 };

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Key {
    /// Pitch class of the tonic, 0 = C.
    pub tonic: u8,
    pub minor: bool,
}

impl Key {
    pub fn name(&self) -> String {
        format!("{} {}", NOTE_NAMES[self.tonic as usize], if self.minor { "minor" } else { "major" })
    }

    /// Index 0..24: majors 0..12, minors 12..24.
    pub fn index(&self) -> usize {
        self.tonic as usize + if self.minor { 12 } else { 0 }
    }

    fn from_index(k: usize) -> Key {
        Key { tonic: (k % 12) as u8, minor: k >= 12 }
    }

    pub fn relative(&self) -> Key {
        if self.minor {
            Key { tonic: (self.tonic + 3) % 12, minor: false }
        } else {
            Key { tonic: (self.tonic + 9) % 12, minor: true }
        }
    }
}

#[derive(Clone, Copy, Debug)]
pub struct Candidate {
    pub key: Key,
    /// Posterior probability, 0..1.
    pub score: f32,
}

#[derive(Clone, Debug)]
pub struct Estimate {
    /// All 24 keys, best first.
    pub ranked: Vec<Candidate>,
    /// Posterior of every key, indexed by `Key::index`.
    pub posterior: [f32; 24],
    /// 0..1: the chance the winner is right, zero for unpitched material.
    pub confidence: f32,
}

impl Estimate {
    fn new(posterior: [f32; 24], calibration: Calibration, pitched: f32) -> Self {
        let mut ranked: Vec<Candidate> =
            posterior.iter().enumerate().map(|(k, &score)| Candidate { key: Key::from_index(k), score }).collect();
        ranked.sort_by(|a, b| b.score.total_cmp(&a.score));
        Self { confidence: calibration.apply(ranked[0].score) * pitched, ranked, posterior }
    }
}

/// Gate from `PitchHistogram::tonality` (0..1), so that noise, which still
/// yields *some* most likely key, reads as unconfident.
fn pitched(tonality: f32) -> f32 {
    ((tonality - 0.10) / 0.15).clamp(0.0, 1.0)
}

fn posterior(chroma: &[f32; 12], p: &Profile) -> Option<[f32; 24]> {
    let total: f32 = chroma.iter().sum();
    if total <= 0.0 {
        return None;
    }
    let (major, minor) = (p.major.map(f32::ln), p.minor.map(f32::ln));
    let mut ll = [0.0f32; 24];
    for (k, l) in ll.iter_mut().enumerate() {
        let profile = if k < 12 { &major } else { &minor };
        *l = (0..12).map(|i| chroma[(i + k) % 12] * profile[i]).sum::<f32>() / total;
    }
    let best = ll.iter().cloned().fold(f32::MIN, f32::max);
    let mut post = ll.map(|l| (p.temperature * (l - best)).exp());
    let z: f32 = post.iter().sum();
    post.iter_mut().for_each(|x| *x /= z);
    Some(post)
}

/// Score all 24 keys for one source mode's chroma. `tonality` gates the
/// confidence (see `pitched`).
pub fn estimate(chroma: &[f32; 12], tonality: f32, mode: SourceMode) -> Option<Estimate> {
    let profile = &PROFILES[mode as usize];
    Some(Estimate::new(posterior(chroma, profile)?, profile.calibration, pitched(tonality)))
}

/// Auto: the mean of the modes' posteriors, each with its mode's tonality.
/// Modes that agree reinforce each other, which beats trusting whichever
/// single mode is most confident.
pub fn combine(parts: &[(&Estimate, f32)]) -> Option<Estimate> {
    if parts.is_empty() {
        return None;
    }
    let mut post = [0.0f32; 24];
    for (e, _) in parts {
        post.iter_mut().zip(&e.posterior).for_each(|(p, x)| *p += x / parts.len() as f32);
    }
    let gate = parts.iter().map(|&(_, t)| pitched(t)).fold(0.0, f32::max);
    Some(Estimate::new(post, AUTO_CALIBRATION, gate))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn profiles_identify_themselves_in_every_key() {
        for mode in SourceMode::ALL {
            let p = &PROFILES[mode as usize];
            for t in 0..12 {
                for (dist, minor) in [(&p.major, false), (&p.minor, true)] {
                    let mut c = [0.0f32; 12];
                    for i in 0..12 {
                        c[(i + t) % 12] = dist[i];
                    }
                    let e = estimate(&c, 1.0, mode).unwrap();
                    assert_eq!(e.ranked[0].key, Key { tonic: t as u8, minor }, "{mode:?}");
                }
            }
        }
    }

    #[test]
    fn posterior_is_a_distribution_and_confidence_is_gated() {
        let c = [1.0, 0.0, 0.5, 0.0, 0.8, 0.4, 0.0, 0.9, 0.0, 0.5, 0.0, 0.3];
        let e = estimate(&c, 1.0, SourceMode::Guitar).unwrap();
        assert!((e.posterior.iter().sum::<f32>() - 1.0).abs() < 1e-4);
        assert_eq!(e.ranked[0].score, e.posterior[e.ranked[0].key.index()]);
        assert!(e.confidence > 0.0);
        assert_eq!(estimate(&c, 0.05, SourceMode::Guitar).unwrap().confidence, 0.0);
        assert!(estimate(&[0.0; 12], 1.0, SourceMode::Guitar).is_none());
        let auto = combine(&[(&e, 1.0), (&e, 0.0)]).unwrap();
        assert_eq!(auto.ranked[0].key, e.ranked[0].key);
    }

    #[test]
    fn relative_keys() {
        let c = Key { tonic: 0, minor: false };
        assert_eq!(c.relative().name(), "A minor");
        assert_eq!(c.relative().relative(), c);
    }
}
