//! Key estimation: the likelihood of a chroma vector under each key's
//! pitch-class distribution, turned into a calibrated posterior.

use crate::chroma::SourceMode;

pub const NOTE_NAMES: [&str; 12] = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"];

/// Platt scaling: maps the winning key's posterior to the chance it is right.
#[derive(Clone, Copy, Debug)]
pub struct Calibration {
    slope: f32,
    offset: f32,
}

impl Calibration {
    fn apply(self, p: f32) -> f32 {
        let p = p.clamp(1e-4, 1.0 - 1e-4);
        1.0 / (1.0 + (-(self.slope * (p / (1.0 - p)).ln() + self.offset)).exp())
    }
}

/// Key model for one source mode, fitted on Logic's Apple Loops by
/// `scripts/bench/train.py` (rerun it when the chroma changes).
#[derive(Debug)]
pub struct Profile {
    /// Pitch-class distributions of a major and a minor key with tonic C:
    /// the mean chroma of loops in that key. Krumhansl-Kessler and Temperley
    /// describe classical music; these come from riffs and grooves, with a
    /// heavier tonic and the flat seventh of Dorian and Mixolydian material,
    /// and they fold in the harmonics this mode's peak picking lets through.
    major: [f32; 12],
    minor: [f32; 12],
    /// Scales log-likelihood differences before the softmax over keys.
    temperature: f32,
    calibration: Calibration,
}

